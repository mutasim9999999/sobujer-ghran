function setMobileNavigationActive(isProductRoute) {
  const isShopRoute = isProductRoute || window.location.hash === "#shop";
  document.querySelectorAll(".mobile-dock a").forEach((link) => {
    const isCurrent = isShopRoute ? link.hash === "#shop" : link.hash === "#top";
    link.classList.toggle("is-current", isCurrent);
    if (isCurrent) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
}

function handlePageRoute() {
  const productRoutePrefix = "#product/";
  const isProductRoute = window.location.hash.startsWith(productRoutePrefix);
  const homeView = document.querySelector("#homeView");
  const productView = document.querySelector("#productView");

  if (isProductRoute) {
    openSearchAfterHomeNavigation = false;
    searchOpenerAfterHomeNavigation = null;
    setMobileNavigationActive(true);
    if (!searchPanel.hidden) closeSearch();
    const key = window.location.hash.slice(productRoutePrefix.length);
    const productExists = Object.prototype.hasOwnProperty.call(products, key);
    const notFound = document.querySelector("#pdpNotFound");
    const content = document.querySelector("#pdpContent");

    homeView.hidden = true;
    productView.hidden = false;
    content.hidden = !productExists;
    notFound.hidden = productExists;

    if (productExists) {
      if (activeProductKey !== key) productQuantity = 1;
      activeProductKey = key;
      renderProductDetails(key);
      window.scrollTo(0, 0);
      window.requestAnimationFrame(() => document.querySelector("#pdpTitle").focus({ preventScroll: true }));
    } else {
      activeProductKey = null;
      productView.setAttribute("aria-labelledby", "pdpNotFoundTitle");
      document.title = translations[language]["pdp.notFoundTitle"];
      window.scrollTo(0, 0);
      window.requestAnimationFrame(() => document.querySelector("#pdpNotFoundTitle").focus({ preventScroll: true }));
    }
    return;
  }

  const wasProductRoute = activeProductKey !== null || !productView.hidden;
  activeProductKey = null;
  setMobileNavigationActive(false);
  productView.hidden = true;
  homeView.hidden = false;
  document.title = homePageTitle;

  if (wasProductRoute && window.location.hash.length > 1) {
    const targetId = window.location.hash.slice(1);
    window.requestAnimationFrame(() => {
      const target = document.getElementById(targetId);
      if (target) target.scrollIntoView({ block: "start" });
    });
  }

  if (openSearchAfterHomeNavigation) {
    openSearchAfterHomeNavigation = false;
    const opener = searchOpenerAfterHomeNavigation;
    searchOpenerAfterHomeNavigation = null;
    window.requestAnimationFrame(() => {
      toggleSearch(true, opener);
      window.scrollTo({ top: 0, behavior: "smooth" });
    });
  }
}

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const text = translations[language][element.dataset.i18n];
    if (text) element.textContent = text;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const text = translations[language][element.dataset.i18nAria];
    if (text) element.setAttribute("aria-label", text);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const text = translations[language][element.dataset.i18nAlt];
    if (text) element.alt = text;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const text = translations[language][element.dataset.i18nPlaceholder];
    if (text) element.placeholder = text;
  });
  languageSwitch.setAttribute("aria-label", language === "en" ? "Switch language to Bangla" : "Switch language to English");
  document.querySelectorAll(".price-value, .product-price").forEach((element) => {
    const price = Number(element.dataset.price);
    if (Number.isFinite(price)) element.textContent = formatPrice(price);
  });
  renderCart();
  updateProductResults(languageInitialized);
  languageInitialized = true;
  if (activeProductKey) renderProductDetails(activeProductKey);
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove("is-visible"), 2800);
}

function openCart() {
  inertPageElements = Array.from(document.body.children)
    .filter((element) => element instanceof HTMLElement && element !== cartDrawer && element !== drawerBackdrop && element !== toast)
    .map((element) => ({ element, wasInert: element.inert }));
  inertPageElements.forEach(({ element }) => {
    element.inert = true;
  });
  cartDrawer.inert = false;
  cartDrawer.classList.add("is-open");
  cartDrawer.setAttribute("aria-hidden", "false");
  drawerBackdrop.hidden = false;
  document.body.classList.add("drawer-open");
  document.querySelector("#cartClose").focus();
}

function closeCart() {
  cartDrawer.classList.remove("is-open");
  cartDrawer.setAttribute("aria-hidden", "true");
  cartDrawer.inert = true;
  drawerBackdrop.hidden = true;
  inertPageElements.forEach(({ element, wasInert }) => {
    element.inert = wasInert;
  });
  inertPageElements = [];
  document.body.classList.remove("drawer-open");
  document.querySelector("#cartToggle").focus();
}

function getCartFocusableElements() {
  return Array.from(cartDrawer.querySelectorAll(
    'a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'
  )).filter((element) => element.getClientRects().length > 0 && getComputedStyle(element).visibility !== "hidden");
}

function renderCart() {
  const entries = Array.from(cart.entries());
  const quantity = entries.reduce((sum, [, count]) => sum + count, 0);
  const subtotal = entries.reduce((sum, [key, count]) => sum + products[key].price * count, 0);
  cartCount.textContent = String(quantity);
  cartCount.setAttribute("aria-label", `${quantity} ${language === "en" ? "items" : "টি পণ্য"}`);
  cartSubtotal.textContent = formatPrice(subtotal);
  cartEmpty.hidden = quantity > 0;
  cartBottom.hidden = quantity === 0;
  cartItems.innerHTML = entries.map(([key, count]) => {
    const product = products[key];
    const productName = translations[language][product.nameKey];
    return `<article class="cart-item">
      <div class="cart-item__image"><img src="${product.image}" alt=""></div>
      <div class="cart-item__info">
        <strong>${productName}</strong>
        <span>${product.detail}</span>
        <div class="cart-item__quantity" role="group" aria-label="${translations[language]["cart.quantityFor"].replace("{product}", productName)}">
          <button type="button" data-quantity="${key}" data-change="-1" aria-label="${translations[language]["cart.decrease"].replace("{product}", productName)}"><span aria-hidden="true">−</span></button>
          <span>${language === "bn" ? new Intl.NumberFormat("bn-BD").format(count) : count}</span>
          <button type="button" data-quantity="${key}" data-change="1" aria-label="${translations[language]["cart.increase"].replace("{product}", productName)}"><span aria-hidden="true">+</span></button>
        </div>
      </div>
      <span class="cart-item__price">${formatPrice(product.price * count)}</span>
    </article>`;
  }).join("");
}

function addToCart(key, quantity) {
  if (!Object.prototype.hasOwnProperty.call(products, key)) {
    console.error(`Cannot add unknown product "${key}" to the cart.`);
    showToast(translations[language]["pdp.notFoundBody"]);
    return;
  }
  if (!Number.isSafeInteger(quantity) || quantity < 1) {
    console.error(`Cannot add invalid quantity "${quantity}" for product "${key}".`);
    showToast(translations[language]["pdp.quantityError"]);
    return;
  }

  cart.set(key, (cart.get(key) || 0) + quantity);
  renderCart();
  const productName = getProductName(products[key]);
  const locale = language === "bn" ? "bn-BD" : "en-BD";
  const quantityPrefix = quantity > 1 ? `${new Intl.NumberFormat(locale).format(quantity)} × ` : "";
  showToast(`${quantityPrefix}${productName} · ${translations[language]["toast.added"]}`);
}

